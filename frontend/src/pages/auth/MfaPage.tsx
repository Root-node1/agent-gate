import { useEffect, useState, type FormEvent } from 'react'
import { Link, Navigate, useLocation, useNavigate } from 'react-router'
import { verifyMfa } from '../../api/auth'
import { useSession } from '../../session/context'
import AuthField from './AuthField'
import AuthShell from './AuthShell'
import SixDigitCodeInput from './SixDigitCodeInput'

interface MfaLocationState {
  email?: string
  types?: string[]
}

export default function MfaPage() {
  const { authenticationError, authenticationStatus, pendingFlow, refreshSession } = useSession()
  const location = useLocation()
  const navigate = useNavigate()
  const state = location.state as MfaLocationState | null
  const types = state?.types ?? pendingFlow?.types ?? []
  const [code, setCode] = useState<string[]>(Array(6).fill(''))
  const [recoveryCode, setRecoveryCode] = useState('')
  const [recoveryMode, setRecoveryMode] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [submitting, setSubmitting] = useState(false)
  const [secondsUntilRefresh, setSecondsUntilRefresh] = useState(30)

  useEffect(() => {
    const timer = window.setInterval(
      () => setSecondsUntilRefresh(30 - (Math.floor(Date.now() / 1000) % 30)),
      1000,
    )
    return () => window.clearInterval(timer)
  }, [])

  async function submit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault()
    setSubmitting(true)
    setError(null)
    try {
      await verifyMfa(recoveryMode || !types.includes('totp') ? recoveryCode.trim() : code.join(''))
      const session = await refreshSession()
      if (session.status !== 'authenticated') {
        throw new Error('Verification succeeded, but the dashboard session could not be confirmed.')
      }
      setCode(Array(6).fill(''))
      setRecoveryCode('')
      navigate('/app', { replace: true })
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : 'The verification code was not accepted.')
      setSubmitting(false)
    }
  }

  const hasTotp = types.includes('totp')
  const hasRecovery = types.includes('recovery_codes')
  if (authenticationStatus === 'loading') {
    return <p className="session-gate" role="status">Checking your verification session…</p>
  }
  if (authenticationStatus === 'error') {
    return (
      <main className="session-gate">
        <h1>Could not verify your session</h1>
        <p role="alert">{authenticationError}</p>
        <button
          type="button"
          className="btn btn-primary"
          onClick={() => void refreshSession().catch(() => undefined)}
        >
          Try again
        </button>
      </main>
    )
  }
  if (authenticationStatus === 'authenticated') return <Navigate to="/app" replace />
  if (!state && !pendingFlow) {
    return (
      <AuthShell eyebrow="Additional security" title="Start sign-in again">
        <p className="auth-note">This verification step expired. Sign in again to continue.</p>
        <Link to="/login" className="btn btn-primary btn-block">Back to sign in</Link>
      </AuthShell>
    )
  }

  return (
    <AuthShell
      eyebrow="Additional security"
      title="Verify it’s you"
      description={
        state?.email
          ? `Enter a code for ${state.email}.`
          : 'Enter a code from an enrolled authenticator.'
      }
    >
      <p className="auth-warning" role="note">
        {hasTotp
          ? `Authenticator codes refresh in ${secondsUntilRefresh} seconds. Codes are generated by your app and cannot be resent.`
          : 'Use a saved recovery code from your account security setup.'}
      </p>
      <form onSubmit={submit}>
        {recoveryMode || !hasTotp ? (
          <AuthField
            label="Recovery code"
            autoComplete="one-time-code"
            autoCapitalize="characters"
            required
            value={recoveryCode}
            onChange={(event) => setRecoveryCode(event.target.value)}
          />
        ) : (
          <>
            <p className="field-label">Six-digit authenticator code</p>
            <SixDigitCodeInput
              value={code}
              onChange={setCode}
              disabled={submitting}
              error={Boolean(error)}
            />
          </>
        )}
        {error ? <p className="auth-error" role="alert">{error}</p> : null}
        <button
          type="submit"
          className="btn btn-primary btn-block"
          disabled={submitting || (!recoveryMode && hasTotp && code.some((digit) => !digit))}
        >
          {submitting ? 'Verifying…' : 'Verify and continue'}
        </button>
      </form>
      {hasRecovery ? (
        <div className="auth-actions">
          <button
            type="button"
            className="auth-text-button"
            onClick={() => {
              setRecoveryMode((mode) => !mode)
              setCode(Array(6).fill(''))
              setRecoveryCode('')
              setError(null)
            }}
          >
            {recoveryMode ? 'Use authenticator app instead' : 'Use a recovery code'}
          </button>
        </div>
      ) : null}
      <Link className="auth-back-link" to="/login">Cancel and return to sign in</Link>
    </AuthShell>
  )
}
