import { useEffect, useState, type FormEvent } from 'react'
import { Link, useLocation, useNavigate } from 'react-router'
import { setRememberSession, verifyMfa } from '../api/auth'
import { SixDigitCodeInput } from './AuthFields'
import AuthShell from './AuthShell'

interface MfaState {
  email?: string
  remember?: boolean
  types?: string[]
}

export default function MfaPage() {
  const location = useLocation()
  const navigate = useNavigate()
  const state = location.state as MfaState | null
  const [code, setCode] = useState<string[]>(Array(6).fill(''))
  const [recoveryCode, setRecoveryCode] = useState('')
  const [recoveryMode, setRecoveryMode] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [submitting, setSubmitting] = useState(false)
  const [secondsUntilRefresh, setSecondsUntilRefresh] = useState(30)
  const supportsTotp = state?.types?.includes('totp') ?? false
  const supportsRecovery = state?.types?.includes('recovery_codes') ?? false

  useEffect(() => {
    const timer = window.setInterval(
      () => setSecondsUntilRefresh(30 - (Math.floor(Date.now() / 1000) % 30)),
      1000,
    )
    return () => window.clearInterval(timer)
  }, [])

  async function submit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault()
    setSubmitting(true)
    setError(null)
    try {
      await verifyMfa(recoveryMode || !supportsTotp ? recoveryCode.trim() : code.join(''))
      await setRememberSession(state?.remember ?? false)
      navigate('/app', { replace: true })
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : 'The code is invalid or has expired.')
      setSubmitting(false)
    }
  }

  if (!state) {
    return (
      <AuthShell eyebrow="Sign-in verification" title="Start sign-in again">
        <p className="auth-error" role="alert">
          This verification step expired. Sign in again to continue.
        </p>
        <Link to="/login" className="btn btn-primary btn-block">Back to sign in</Link>
      </AuthShell>
    )
  }

  return (
    <AuthShell
      eyebrow="Additional security"
      title="Verify it’s you"
      description={
        state.email
          ? `Enter a code for the account ${state.email}.`
          : 'Enter a code from your authenticator app or a saved recovery code.'
      }
    >
      <p className="auth-warning" role="note">
        {supportsTotp
          ? `Authenticator codes refresh in ${secondsUntilRefresh} seconds. Codes are generated by your app and cannot be resent.`
          : 'Use a saved recovery code from your account security setup.'}
      </p>
      <form onSubmit={submit}>
        {recoveryMode || !supportsTotp ? (
          <div className="field">
            <label htmlFor="recovery-code">Recovery code</label>
            <input
              id="recovery-code"
              type="text"
              autoComplete="one-time-code"
              autoCapitalize="characters"
              required
              value={recoveryCode}
              onChange={(event) => setRecoveryCode(event.target.value)}
              aria-invalid={Boolean(error)}
            />
          </div>
        ) : (
          <>
            <p className="field-label">Six-digit authenticator code</p>
            <SixDigitCodeInput
              value={code}
              onChange={setCode}
              disabled={submitting}
              error={Boolean(error)}
            />
          </>
        )}
        {error ? <p className="auth-error" role="alert">{error}</p> : null}
        <button type="submit" className="btn btn-primary btn-block" disabled={submitting}>
          {submitting ? 'Verifying…' : 'Verify and continue'}
        </button>
      </form>

      {supportsRecovery ? (
        <div className="auth-actions">
          <button
            type="button"
            className="auth-text-button"
            onClick={() => {
              setRecoveryMode((mode) => !mode)
              setCode(Array(6).fill(''))
              setRecoveryCode('')
              setError(null)
            }}
          >
            {recoveryMode ? 'Use authenticator app instead' : 'Use a recovery code'}
          </button>
        </div>
      ) : null}
      <Link className="auth-back-link" to="/login">Cancel and return to sign in</Link>
    </AuthShell>
  )
}
